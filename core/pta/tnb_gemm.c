static void put(struct tnb_reg *out, size_t index, uint32_t value)
{
	out[index].value = value;
}


bool tnb_gemm_emit(uint32_t m, uint32_t k, uint32_t n,
		   struct tnb_reg out[TNB_GEMM_WRITES])
{
	uint32_t width = n - 1;
	uint32_t stride = n / 4 - 1;

	if (m < 1 || m > PTA_TNB_GEMM_M_MAX || k < PTA_TNB_GEMM_K_MIN || k > PTA_TNB_GEMM_K_MAX ||
	    n < PTA_TNB_GEMM_N_MIN || n > PTA_TNB_GEMM_N_MAX ||
	    k % 32 || n % PTA_TNB_GEMM_N_ALIGN ||
	    k * n > PTA_TNB_GEMM_B_MAX)
		return false;

	memcpy(out, skeleton, sizeof(skeleton));
	put(out, 6, (m + 1) << 4);
	put(out, 8, 0x00010000 | m);
	put(out, 9, ((k - 1) << 16) | k);
	put(out, 11, m);
	put(out, 12, k * n);
	put(out, 13, k);
	put(out, 14, 0x01010000 | n);
	put(out, 16, (k + 63) / 64);
	put(out, 28, k / 16);
	put(out, 30, 0x00010000 | m);
	put(out, 31, k);
	put(out, 54, (m - 1) << 16);
	put(out, 55, width);
	put(out, 64, m - 1);
	put(out, 65, (stride << 16) | stride);
	put(out, 66, (width << 16) | width);
	put(out, 73, width);
	put(out, 74, (m - 1) << 16);
	if (m == 1) {
		put(out, 3, 0);
		put(out, 5, 0);
		put(out, 28, 4);
		put(out, 29, 0x0ffffffd);
		put(out, 65, 0);
	}
	return true;
}
